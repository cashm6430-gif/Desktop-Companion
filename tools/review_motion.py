def gif_from_sequence(p, target, background, mask_paste, palette_indices, dither, optimize=None, log=print):
    """One palette for the whole cycle keeps the GIF free of colour flicker.

    `mask_paste`, `palette_indices`, `dither` and `optimize` reproduce the
    flattening, palette seeding and save flags of the earlier scripts, so the
    approved GIFs and the new ones are built the same way. Note that passing
    `optimize=False` and omitting it produce different bytes, which is why the
    flag is optional rather than defaulted. This is a review artifact assembled
    from actual Native frames; the desktop pet animates the MOC3 and never
    plays this file.
    """
    sequence = sorted(p["sequence"].glob("frame-*.png"))
    if len(sequence) != p["frames"]:
        log(f"  skip {target.name}: {len(sequence)}/{p['frames']} frames")
        return
    rgb = []
    for path in sequence:
        sprite = Image.open(path).convert("RGBA").resize((420, 420), Image.Resampling.LANCZOS)
        if mask_paste:
            matte = Image.new("RGB", sprite.size, background)
            matte.paste(sprite, (0, 0), sprite)
            rgb.append(matte)
        else:
            matte = Image.new("RGBA", sprite.size, background)
            matte.alpha_composite(sprite)
            rgb.append(matte.convert("RGB"))
    picks = list(palette_indices) if palette_indices is not None else list(range(0, len(rgb), 10))
    overview = Image.new("RGB", (420 * len(picks), 420))
    for i, index in enumerate(picks):
        overview.paste(rgb[index], (i * 420, 0))
    palette = overview.quantize(colors=255)
    frames = [frame.quantize(palette=palette, dither=dither) for frame in rgb]
    options = {"save_all": True, "append_images": frames[1:],
               "duration": [[70, 70, 60][i % 3] for i in range(len(frames))], "loop": 0, "disposal": 2}
    if optimize is not None:
        options["optimize"] = optimize
    frames[0].save(target, **options)
    log(f"  wrote {target.relative_to(ROOT)}")


