"""Single approval entry for every Live2D motion.

One command renders the authored key poses and the full native sequence of a
clip, composes the review sheets and the loop GIF under art/live2d/review/,
and (with --validate) checks the captures for clipping and a drifting floor.

    python tools/review_motion.py grass
    python tools/review_motion.py busy-laptop --revision 3 --validate
    python tools/review_motion.py idle --no-render
    python tools/review_motion.py idle --draft

Use --draft for a new review: it preserves approved sheets, captures into a
fresh build/review-runs directory, and records source/deployment provenance.

The grass and seated-laptop sheets keep the exact layouts of the earlier
create_motion_review.py / create_laptop_review.py scripts, so the approved
artifacts can be regenerated byte for byte. Clips without keyframes (idle,
busy-stand, delete) get a frame sheet sampled from their rendered sequence plus
the loop GIF.

Captures come from build/DesktopCompanion.exe --render-motion / --review-motion,
which read build/assets/. Always run native captures, never generated art.
"""
